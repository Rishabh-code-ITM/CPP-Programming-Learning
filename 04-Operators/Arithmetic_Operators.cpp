#include <iostream>                                 // Input output stream library
using namespace std;                                // std namespace use karne ke liye

int main() {                                        // Program yahin se start hota hai (main function)
    int a = 17, b = 5;                              // Do numbers declare kiye
    cout << "a + b = " << a + b << endl;            // Addition
    cout << "a - b = " << a - b << endl;            // Subtraction
    cout << "a * b = " << a * b << endl;            // Multiplication
    cout << "a / b = " << a / b << endl;            // Division: int / int ka result int aata hai (decimal part hat jata hai)
    cout << "a % b = " << a % b << endl;            // Modulus: remainder deta hai
    return 0;                                       // Program successfully khatam
}                                                   // main function end
