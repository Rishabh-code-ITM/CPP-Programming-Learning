#include <iostream>                                 // Input output stream library
using namespace std;                                // std namespace use karne ke liye

int main() {                                        // Program yahin se start hota hai (main function)
    int a;                                          // Sirf declaration, abhi value nahi di
    a = 10;                                         // Baad mein value assign ki (initialization)
    int b = 20;                                     // Declaration aur initialization ek saath
    int x = 1, y = 2, z = 3;                        // Ek line mein multiple variables declare kiye
    cout << "a = " << a << ", b = " << b << endl;   // a aur b print karo
    cout << "x = " << x << ", y = " << y << ", z = " << z << endl;   // x, y, z print karo
    return 0;                                       // Program successfully khatam
}                                                   // main function end
