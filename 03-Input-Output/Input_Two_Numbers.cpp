#include <iostream>                                 // Input output stream library
using namespace std;                                // std namespace use karne ke liye

int main() {                                        // Program yahin se start hota hai (main function)
    int a, b;                                       // Do numbers ke variables
    cout << "Enter first number: ";                 // Pehla number maango
    cin >> a;                                       // cin >> se keyboard se input milta hai
    cout << "Enter second number: ";                // Dusra number maango
    cin >> b;                                       // Dusra number input lo
    cout << "Sum = " << a + b << endl;              // Dono ka sum print karo
    return 0;                                       // Program successfully khatam
}                                                   // main function end
