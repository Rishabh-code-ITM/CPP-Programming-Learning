#include <iostream>                                 // Input output stream library
using namespace std;                                // std namespace use karne ke liye

int main() {                                        // Program yahin se start hota hai (main function)
    cout << "New\nLine" << endl;                    // \n se nayi line shuru hoti hai
    cout << "Tab\tSpace" << endl;                   // \t se tab jitna gap aata hai
    cout << "Double quote: \"Hi\"" << endl;         // \" se string ke andar double quote print hota hai
    cout << "Backslash: \\" << endl;                // \\ se ek backslash print hota hai
    cout << "Single quote: \'A\'" << endl;          // \' se single quote print hota hai
    return 0;                                       // Program successfully khatam
}                                                   // main function end
