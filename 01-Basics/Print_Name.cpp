#include <iostream>                                 // Input output stream library
using namespace std;                                // std namespace use karne ke liye

int main() {                                        // Program yahin se start hota hai (main function)
    string name = "Rahul";                          // String variable mein naam store kiya (yahan apna naam likho)
    int age = 20;                                   // Age ke liye integer variable
    cout << "My name is " << name << endl;          // << se multiple cheezein ek saath print kar sakte hain
    cout << "My age is " << age << endl;            // Age print karo
    return 0;                                       // Program successfully khatam
}                                                   // main function end
